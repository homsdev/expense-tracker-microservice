package com.homsdev.transactions_service.dto;

import com.homsdev.transactions_service.enums.TransactionType;
import io.swagger.v3.oas.annotations.media.Schema;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.math.BigDecimal;

@Data
@AllArgsConstructor
@NoArgsConstructor
@Schema(description = "A transaction returned by the API, including its category")
public class TransactionResponse {
    @Schema(description = "Unique transaction id (UUID) generated by the server", example = "7d4e2a10-3b8f-4f5e-9a6c-1e2d3f4a5b6c")
    private String id;
    @Schema(description = "Kind of transaction: INCOME, EXPENSE or TRANSFER", example = "EXPENSE")
    private TransactionType type;
    @Schema(description = "Free text describing the transaction", example = "Weekly groceries")
    private String description;
    @Schema(description = "ISO 4217 currency code", example = "USD")
    private String currency;
    @Schema(description = "Transaction amount with its decimal places", example = "25.50")
    private BigDecimal amount;
    @Schema(description = "Category the transaction belongs to")
    private CategoryResponse category;
}
