package com.homsdev.transactions_service.dto;


import io.swagger.v3.oas.annotations.media.Schema;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;

@Data
@AllArgsConstructor
@NoArgsConstructor
@Schema(description = "A category returned by the API")
public class CategoryResponse {
    @Schema(description = "Unique category id (UUID) generated by the server", example = "c0a80121-7b5e-4c3a-9d1f-2a4b6c8d9e0f")
    private String id;
    @Schema(description = "Name of the category", example = "Groceries")
    private String name;
}
