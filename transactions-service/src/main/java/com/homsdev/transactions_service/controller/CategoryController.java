package com.homsdev.transactions_service.controller;

import com.homsdev.transactions_service.dto.CategoryResponse;
import com.homsdev.transactions_service.dto.CreateCategoryRequest;
import com.homsdev.transactions_service.exception.GlobalExceptionHandler;
import com.homsdev.transactions_service.service.CategoryService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.media.Content;
import io.swagger.v3.oas.annotations.media.ExampleObject;
import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.tags.Tag;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.http.HttpStatus;
import org.springframework.web.bind.annotation.*;

import java.util.List;

@RestController
@RequestMapping("/api/v1/category")
@RequiredArgsConstructor
@Slf4j
@Tag(name = "Categories", description = "Create, read and deactivate expense categories. "
		+ "Deleting a category is a soft delete: it disappears from the list but its data is kept. "
		+ "Base path: /api/v1/category")
public class CategoryController {

    private final CategoryService categoryService;

    @GetMapping
    @ResponseStatus(HttpStatus.OK)
    @Operation(summary = "List active categories",
            description = "Returns every category that has not been deactivated. Deactivated categories are excluded.")
    @ApiResponse(responseCode = "200", description = "Active categories. The list is empty when none exist.")
    public List<CategoryResponse> getAllCategories() {
        return categoryService.getAllCategories();
    }

    @GetMapping("/{id}")
    @ResponseStatus(HttpStatus.OK)
    @Operation(summary = "Get a category by id",
            description = "Returns the category with the given id.")
    @ApiResponse(responseCode = "200", description = "The requested category")
    @ApiResponse(responseCode = "404", description = "No category has that id",
            content = @Content(mediaType = "application/problem+json",
                    schema = @Schema(type = "object"),
                    examples = @ExampleObject(value = GlobalExceptionHandler.CATEGORY_NOT_FOUND_EXAMPLE)))
    public CategoryResponse getCategoryById(
            @Parameter(description = "Category id (UUID)", example = "c0a80121-7b5e-4c3a-9d1f-2a4b6c8d9e0f")
            @PathVariable String id) {
        return categoryService.getCategoryById(id);
    }

    @PostMapping
    @ResponseStatus(HttpStatus.CREATED)
    @Operation(summary = "Create a category",
            description = "Creates a new active category with the given name. The id is generated by the server.")
    @ApiResponse(responseCode = "201", description = "Category created. The response contains the generated id.")
    public CategoryResponse createCategory(@RequestBody CreateCategoryRequest request) {
        return categoryService.createCategory(request);
    }

    @DeleteMapping("/{id}")
    @ResponseStatus(HttpStatus.NO_CONTENT)
    @Operation(summary = "Deactivate a category",
            description = "Soft delete: marks the category as inactive so it no longer appears in the list. "
                    + "The stored data is kept.")
    @ApiResponse(responseCode = "204", description = "Category deactivated. No response body.")
    @ApiResponse(responseCode = "404", description = "No category has that id",
            content = @Content(mediaType = "application/problem+json",
                    schema = @Schema(type = "object"),
                    examples = @ExampleObject(value = GlobalExceptionHandler.CATEGORY_NOT_FOUND_EXAMPLE)))
    public void deleteCategory(
            @Parameter(description = "Category id (UUID)", example = "c0a80121-7b5e-4c3a-9d1f-2a4b6c8d9e0f")
            @PathVariable String id) {
        categoryService.deleteCategory(id);
    }
}
